// ─── Task ──────────────────────────────────────────────────────────────────

struct WidgetTask: Codable, Identifiable, Hashable {
    let id: String
    let title: String
    let completed: Bool
    let startHour: Int?
    let startMinute: Int?
    let type: String?         // "task" | "deadline" | "break"
    let complexity: String?   // "hard" | "medium" | "easy" | nil — "hard" == a Deep Work block

    var timeLabel: String? {
        guard let h = startHour, let m = startMinute else { return nil }
        let h12  = h % 12 == 0 ? 12 : h % 12
        let ampm = h < 12 ? "AM" : "PM"
        return String(format: "%d:%02d %@", h12, m, ampm)
    }

    var minutesFromMidnight: Int? {
        guard let h = startHour else { return nil }
        return h * 60 + (startMinute ?? 0)
    }
}

