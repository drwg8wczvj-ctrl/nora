// ─── Time-of-day phase — drives Part 5's "Smart Widgets" adaptive content.
// Computed from each TimelineEntry's own `date`, not stored in the payload,
// so the whole day's entries can be scheduled up front (see NoraProvider). ──

enum DayPhase: String, Codable {
    case morning, afternoon, evening

    static func forHour(_ hour: Int) -> DayPhase {
        switch hour {
        case 5..<12:  return .morning
        case 12..<18: return .afternoon
        default:      return .evening
        }
    }
}

struct NoraEntry: TimelineEntry {
    let date: Date
    let data: WidgetData
    var phase: DayPhase = .morning
    var isPlaceholder: Bool = false
}

// ─── Shared App Group storage — read by every widget kind, written by the
// main app; also supports one narrow write-back path (a pending-action
// queue) for interactive widget buttons, since the widget extension process
// is never the source of truth for the real task list. ────────────────────

enum WidgetStore {
    static let appGroupID = "group.tech.dongar.nora"
    static let dataKey = "nora_widget_data"
    static let pendingActionsKey = "nora_widget_pending_actions"

    static var defaults: UserDefaults? { UserDefaults(suiteName: appGroupID) }

    static func load() -> WidgetData {
        guard
            let defaults = defaults,
            let jsonString = defaults.string(forKey: dataKey),
            let jsonData = jsonString.data(using: .utf8),
            let data = try? JSONDecoder().decode(WidgetData.self, from: jsonData)
        else { return .placeholder }
        return data
    }

    private static func save(_ data: WidgetData) {
        guard
            let defaults = defaults,
            let jsonData = try? JSONEncoder().encode(data),
            let jsonString = String(data: jsonData, encoding: .utf8)
        else { return }
        defaults.set(jsonString, forKey: dataKey)
    }

    /// Optimistic local update so a tap reflects instantly, before the main
    /// app ever runs — the authoritative change is queued separately (see
    /// enqueuePendingAction) for the JS app's real task list to apply next
    /// time it's foregrounded, exactly like executeAiTool's complete_task.
    static func markTaskCompletedLocally(taskId: String) {
        var data = load()
        var completedDelta = 0
        data.todayTasks = data.todayTasks.map { task in
            guard task.id == taskId, !task.completed else { return task }
            completedDelta = 1
            return WidgetTask(id: task.id, title: task.title, completed: true, startHour: task.startHour, startMinute: task.startMinute, type: task.type, complexity: task.complexity)
        }
        data.completedToday += completedDelta
        save(data)
    }

    static func enqueuePendingAction(type: String, taskId: String) {
        guard let defaults = defaults else { return }
        var actions = pendingActions()
        actions.append(WidgetPendingAction(type: type, taskId: taskId, at: Date().timeIntervalSince1970))
        if let data = try? JSONEncoder().encode(actions), let str = String(data: data, encoding: .utf8) {
            defaults.set(str, forKey: pendingActionsKey)
        }
    }

    static func pendingActions() -> [WidgetPendingAction] {
        guard
            let defaults = defaults,
            let str = defaults.string(forKey: pendingActionsKey),
            let data = str.data(using: .utf8),
            let actions = try? JSONDecoder().decode([WidgetPendingAction].self, from: data)
        else { return [] }
        return actions
    }
}

struct WidgetPendingAction: Codable {
    let type: String   // "complete_task"
    let taskId: String
    let at: TimeInterval
}
